"""ふるい分けのテスト。題名は全社の一覧を目で確かめたときの実例 (題名だけで、株価は含まない)。"""
import pytest

from alchemy_stock.screening import classify_title, is_correction, screen


@pytest.mark.parametrize(
    "title, kinds",
    [
        ("2026年３月期 第２四半期（中間期）決算短信〔日本基準〕（連結）", ["決算短信"]),
        ("2024年3月期 決算説明資料", ["決算の補足資料"]),
        ("2024年３月期第２四半期決算速報値に関するお知らせ", ["決算の速報"]),
        ("通期業績予想の修正に関するお知らせ", ["業績予想の修正"]),
        ("業績予想および配当予想に関するお知らせ", ["業績予想の修正", "配当予想の修正"]),
        ("業績予想と実績との差異に関するお知らせ", ["予想と実績の差異"]),
        ("2019年12月期連結業績と前期実績値との差異に関するお知らせ", ["前期実績との差異"]),
        ("2024年12月売上速報", ["月次の売上"]),
        ("剰余金の配当に関するお知らせ", ["配当の決定"]),
        ("剰余金の配当（増配）に関するお知らせ", ["配当予想の修正", "配当の決定"]),
        ("自己株式取得に係る事項の決定に関するお知らせ", ["自社株買いの決定"]),
        ("自己株式の取得結果及び取得終了に関するお知らせ", ["自社株買いの経過"]),
        ("自己株式立会外買付取引（ToSTNeT-3）による自己株式の買付けに関するお知らせ", ["自社株買いの経過"]),
        ("株主優待制度の導入に関するお知らせ", ["株主優待"]),
        ("ヤフー株式会社による当社株式に対する公開買付けに関する意見表明のお知らせ", ["公開買付け (TOB・MBO)"]),
        ("マイクロソニック株式会社の株式取得（子会社化）に関するお知らせ", ["買収・事業の売り買い"]),
        ("連結子会社の吸収合併に関するお知らせ", ["グループ内の再編"]),
        ("株式会社Xthetaとの資本提携に関するお知らせ", ["提携"]),
        ("第三者割当による新株式の発行に関するお知らせ", ["増資・新株予約権"]),
        ("第６回新株予約権の月間行使状況に関するお知らせ", ["増資の経過"]),
        ("株式の立会外分売に関するお知らせ", ["売出し・立会外分売"]),
        ("公正取引委員会からの課徴金納付命令について", ["不祥事・訴訟・延期"]),
        # 「処分」は自己株式の処分 (株式報酬の手続き) と取り違えない
        ("譲渡制限付株式報酬としての自己株式の処分に関するお知らせ", ["手続き・ガバナンス"]),
        ("当社株式の大規模買付行為等への対応方針（買収への対応方針）の継続について", ["手続き・ガバナンス"]),
        ("代表取締役の異動に関するお知らせ", ["人事・組織"]),
        ("ネットで見つからない珍しい題名", ["未分類"]),
    ],
)
def test_classify_title(title, kinds):
    assert classify_title(title) == kinds


def test_is_correction():
    assert is_correction("「2026年３月期決算短信〔日本基準〕」の一部訂正について")
    assert not is_correction("業績予想の修正に関するお知らせ")


def test_screen():
    companies = {
        "12340": {"code": "12340", "industry": "情報・通信業"},
        "13130": {"code": "13130", "industry": "-"},  # ETF
    }
    disclosures = [
        {"doc_id": "1", "code": "12340", "date": "2026-10-30", "title": "業績予想の修正に関するお知らせ"},
        # 同じ開示が別の区分にも載っている
        {"doc_id": "1", "code": "12340", "date": "2026-10-30", "title": "業績予想の修正に関するお知らせ"},
        {"doc_id": "2", "code": "12340", "date": "2026-10-30", "title": "役員の異動に関するお知らせ"},
        {"doc_id": "3", "code": "12340", "date": "2026-10-31", "title": "「業績予想の修正に関するお知らせ」の一部訂正について"},
        {"doc_id": "4", "code": "13130", "date": "2026-10-30", "title": "業績予想の修正に関するお知らせ"},
    ]
    rows = {r["doc_id"]: r for r in screen(disclosures, companies)}
    assert len(rows) == 4
    assert rows["1"]["dropped_by"] is None
    assert rows["1"]["event_id"] == "12340_2026-10-30"
    assert rows["2"]["dropped_by"] == "b.種類"
    assert rows["3"]["dropped_by"] == "a.訂正"
    assert rows["4"]["dropped_by"] == "c.普通の株ではない"
