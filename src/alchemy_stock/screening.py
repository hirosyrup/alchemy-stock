UNCLASSIFIED = "未分類"

GROUP_OF = {r.kind: r.group for r in RULES + FALLBACK_RULES} | {UNCLASSIFIED: UNDECIDED}


def normalize_title(title: str) -> str:
    """全角英数字を半角に揃え、空白を取る。"""
    return re.sub(r"\s+", "", unicodedata.normalize("NFKC", title))


def classify_title(title: str) -> list[str]:
    """題名から種類を決める。当てはまる種類を全部返す。何にも当たらなければ ["未分類"]。"""
    t = normalize_title(title)
    kinds = [r.kind for r in RULES if r.match(t)]
    # 決定と経過の両方に当たったら、決定だけ残す
    for decided, progress in [
        ("自社株買いの決定", "自社株買いの経過"),
        ("公開買付け (TOB・MBO)", "公開買付けの経過"),
        ("増資・新株予約権", "増資の経過"),
        ("売出し・立会外分売", "売出しの経過"),
    ]:
        if decided in kinds and progress in kinds:
            kinds.remove(progress)
    if not kinds:
        kinds = [r.kind for r in FALLBACK_RULES if r.match(t)][:1]
    return kinds or [UNCLASSIFIED]


def is_correction(title: str) -> bool:
    """a. 訂正・取り消しか。新しい材料ではないので落とす。"""
    return bool(CORRECTION.search(normalize_title(title)))


def screen(disclosures: list[dict], companies: dict[str, dict]) -> list[dict]:
    """ふるい分け a・b・c・e を当てる。落としたものも全部返す (落とした理由付き)。

    d (売買の量) は株価が要るので、ここではまだ当てない。
    同じ開示が2つの区分に載っていることがあるので、doc_id で1件にまとめる。
    """
    rows: dict[str, dict] = {}
    for d in disclosures:
        if d["doc_id"] in rows:
            continue
        kinds = classify_title(d["title"])
        groups = sorted({GROUP_OF[k] for k in kinds})
        company = companies.get(d["code"], {})
        if is_correction(d["title"]):
            reason = "a.訂正"
        elif company.get("industry", "-") == "-":
            reason = "c.普通の株ではない"
        elif CANDIDATE not in groups:
            reason = "b.種類"
        else:
            reason = None
        rows[d["doc_id"]] = {
            "doc_id": d["doc_id"],
            "code": d["code"],
            "date": d["date"],
            "title": d["title"],
            "kinds": kinds,
            "groups": groups,
            "dropped_by": reason,
            # e. 同じ会社の同じ日の開示は1つの出来事として束ねる (過去の一覧には時刻が無いので日で束ねる)
            "event_id": f"{d['code']}_{d['date']}",
            "rules_version": RULES_VERSION,
        }
    return list(rows.values())
